/**
 * Effet d'un outil par son nom. Un nom absent de la classification compte
 * pour une écriture : la porte se ferme, elle ne s'ouvre pas.
 */
export function toolEffectOf(name: string): ToolEffect {
  return TOOL_EFFECTS[name as RegisteredToolName] ?? 'write';
}

/** Un outil de ce nom modifie-t-il quelque chose ? (Un nom inconnu, oui.) */
export function isMutatingTool(name: string): boolean {
  return toolEffectOf(name) === 'write';
}
